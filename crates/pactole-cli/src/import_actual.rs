use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

use pactole_import::ActualMigration;

pub(crate) fn run(
    file: PathBuf,
    output: Option<PathBuf>,
    currency: String,
    opening_equity: String,
    opening_date: chrono::NaiveDate,
    payee_metadata_key: Option<String>,
) -> ExitCode {
    let migration = match pactole_import::migrate_actual_database(
        &file,
        &currency,
        &opening_equity,
        opening_date,
        payee_metadata_key.as_deref(),
    ) {
        Ok(migration) => migration,
        Err(error) => {
            eprintln!("error: {error}");
            return ExitCode::FAILURE;
        }
    };

    let source = render(&migration, &opening_date, &currency);
    if let Some(path) = output {
        if let Err(error) = fs::write(&path, source) {
            eprintln!("error: cannot write {}: {error}", path.display());
            return ExitCode::FAILURE;
        }
    } else {
        print!("{source}");
    }
    ExitCode::SUCCESS
}

fn render(migration: &ActualMigration, opening_date: &chrono::NaiveDate, currency: &str) -> String {
    let mut source = String::new();
    source.push_str("; Generated by pactole import-actual\n\n");
    source.push_str(&format!("{} commodity {}\n\n", opening_date, currency));
    source.push_str("; Accounts\n");
    for account in &migration.accounts {
        source.push_str(&format!("{} open {}\n", opening_date, account));
    }
    source.push('\n');

    source.push_str("; Payees\n");
    for payee in &migration.payees {
        source.push_str("payee ");
        source.push_str(&quote(payee));
        source.push('\n');
    }
    if !migration.payees.is_empty() {
        source.push('\n');
    }
    source.push_str(&pactole_storage_fs::format_transactions(
        &migration.transactions,
    ));
    source
}

fn quote(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}
