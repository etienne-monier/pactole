use std::fs::{self, OpenOptions};
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use chrono::{Local, NaiveDate};
use pactole_core::{AccountName, CommodityName};

pub(crate) struct Options {
    pub(crate) ledger: PathBuf,
    pub(crate) account: String,
    pub(crate) currency: String,
    pub(crate) counter_account: String,
    pub(crate) date: Option<NaiveDate>,
    pub(crate) stdout: bool,
    pub(crate) global: bool,
    pub(crate) no_config: bool,
    pub(crate) no_ledger: bool,
}

pub(crate) fn run(options: Options) -> ExitCode {
    let Options {
        ledger,
        account,
        currency,
        counter_account,
        date,
        stdout,
        global,
        no_config,
        no_ledger,
    } = options;
    if no_config && no_ledger {
        eprintln!("error: --no-config and --no-ledger cannot be used together");
        return ExitCode::FAILURE;
    }

    if let Err(err) = AccountName::new(account.clone()) {
        return failure(format!("invalid bank account `{account}`: {err}"));
    }
    if let Err(err) = AccountName::new(counter_account.clone()) {
        return failure(format!(
            "invalid counter account `{counter_account}`: {err}"
        ));
    }
    if let Err(err) = CommodityName::new(currency.clone()) {
        return failure(format!("invalid currency `{currency}`: {err}"));
    }

    let date = date.unwrap_or_else(|| Local::now().date_naive());
    let ledger_source = render_ledger(&date, &account, &currency, &counter_account);
    let config_source = render_config(&account, &currency, &counter_account);

    if !no_ledger && stdout {
        print!("{ledger_source}");
    }

    if !no_ledger && !stdout {
        match create_file_if_missing(&ledger, &ledger_source) {
            Ok(true) => println!("created ledger: {}", ledger.display()),
            Ok(false) => println!("ledger already exists: {}", ledger.display()),
            Err(err) => return failure(format!("cannot initialize {}: {err}", ledger.display())),
        }
    }

    if !no_config {
        let config_path = if global {
            match pactole_config::default_config_path() {
                Some(path) => path,
                None => {
                    return failure(
                        "cannot determine the Pactole configuration directory \
                         (set XDG_CONFIG_HOME or HOME)",
                    );
                }
            }
        } else {
            // Project configuration: next to the ledger.
            ledger
                .parent()
                .unwrap_or_else(|| Path::new(""))
                .join("pactole.toml")
        };

        if let Some(parent) = config_path.parent()
            && let Err(err) = fs::create_dir_all(parent)
        {
            return failure(format!("cannot create {}: {err}", parent.display()));
        }

        match create_file_if_missing(&config_path, &config_source) {
            Ok(true) => println!("created configuration: {}", config_path.display()),
            Ok(false) => println!("configuration already exists: {}", config_path.display()),
            Err(err) => {
                return failure(format!(
                    "cannot initialize {}: {err}",
                    config_path.display()
                ));
            }
        }
    }

    ExitCode::SUCCESS
}

fn render_ledger(date: &NaiveDate, account: &str, currency: &str, counter_account: &str) -> String {
    format!(
        "; Pactole ledger\n\
         ; Generated by `pactole init`.\n\
         ; Add transactions below and run `pactole check ledger.pactole`.\n\n\
         {date} commodity {currency}\n\
         {date} open {account}\n\
         {date} open {counter_account}\n"
    )
}

fn render_config(account: &str, currency: &str, counter_account: &str) -> String {
    format!(
        "# Pactole configuration\n\
         # Generated by `pactole init`.\n\n\
         # This file is optional. Configuration is layered: the project file\n\
         # takes precedence over the global file in the Pactole configuration\n\
         # directory. Uncomment an option below when you want to override its\n\
         # default value.\n\n\
         [validation]\n\
         # Severity of a transaction whose payee has no matching `payee`\n\
         # declaration. Accepted values are \"off\", \"warn\" and \"error\".\n\
         # payee = \"error\"\n\n\
         # Severity of declarations that are never used: an account opened but\n\
         # never used by a transaction or balance assertion, a commodity never\n\
         # used by an amount, or a payee never used by a transaction.\n\
         # Accepted values are \"off\", \"warn\" and \"error\".\n\
         # unused = \"warn\"\n\n\
         [declaration]\n\
         # Optional files where editor integrations should add declarations.\n\
         # Paths are relative to the directory containing the root journal.\n\
         # payees = \"payees.pactole\"\n\
         # accounts = \"accounts.pactole\"\n\
         # commodities = \"commodities.pactole\"\n\n\
         [format]\n\
         # Column at which posting amounts are aligned by `pactole fmt`.\n\
         # The default is 50.\n\
         # posting_width = 50\n\n\
         [reports]\n\
         # Account roots used by `pactole balance`. A root is the first\n\
         # colon-separated component of an account name. For example,\n\
         # `Assets:Checking` belongs to the `Assets` root.\n\
         # Defining one list replaces only that list; omitted lists keep the\n\
         # English defaults shown below. Accounts whose root is not listed are\n\
         # displayed in an `Unclassified` section.\n\
         # assets = [\"Assets\"]\n\
         # liabilities = [\"Liabilities\"]\n\
         # equity = [\"Equity\"]\n\
         # income = [\"Income\"]\n\
         # expenses = [\"Expenses\"]\n\n\
         [import]\n\
         # OFX import settings used by `pactole import-ofx`. These three\n\
         # values are enabled by `pactole init` so the generated configuration\n\
         # can be used immediately.\n\
         bank_account = \"{account}\"\n\
         currency = \"{currency}\"\n\
         default_counter_account = \"{counter_account}\"\n\n\
          # Set this to true to omit the source payee metadata.\n\
          # no_imported_payee = true\n\
          # Omit negative posting amounts and let Pactole infer them.\n\
          # omit_negative_amount = true\n\n\
          # Store the original source payee in transaction metadata while rules\n\
         # are free to replace the visible Pactole payee.\n\
         # payee_metadata_key = \"source_payee\"\n\n\
         # For statements covering several accounts, map each statement\n\
         # account identifier (OFX ACCTID) to its Pactole account. Unmapped\n\
         # identifiers fall back to `bank_account`.\n\
         #\n\
         # [import.accounts]\n\
         # \"00012345678\" = \"Assets:Checking\"\n\
         # \"00098765432\" = \"Assets:Savings\"\n\
         #\n\
         # Rules are evaluated from top to bottom. The first matching rule is\n\
         # used; criteria in one rule are combined with AND. `counter_account`\n\
         # is required, and all other criteria are optional.\n\
         #\n\
         # [[import.rules]]\n\
         # payee_contains = \"supermarket\"\n\
         # payee_in = [\"Market A\", \"Market B\"]\n\
         # payee_regex = \"(?i)market|grocery\"\n\
         # memo_contains = \"weekly shopping\"\n\
         # memo_in = [\"Groceries\", \"Food\"]\n\
         # memo_regex = \"(?i)shop(ping)?\"\n\
         # trntype = \"DEBIT\"\n\
         # trntype_in = [\"DEBIT\", \"POS\"]\n\
         # account = \"00012345678\"\n\
         # direction = \"debit\"\n\
         # counter_account = \"Expenses:Groceries\"\n\
         # payee = \"Supermarket\"\n"
    )
}

fn create_file_if_missing(path: &Path, contents: &str) -> io::Result<bool> {
    if let Some(parent) = path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }

    let mut file = match OpenOptions::new().write(true).create_new(true).open(path) {
        Ok(file) => file,
        Err(err) if err.kind() == io::ErrorKind::AlreadyExists => return Ok(false),
        Err(err) => return Err(err),
    };

    file.write_all(contents.as_bytes())?;
    file.flush()?;
    Ok(true)
}

fn failure(error: impl std::fmt::Display) -> ExitCode {
    eprintln!("error: {error}");
    ExitCode::FAILURE
}
