//! Embeds the built frontend (`web/dist`) into the server binary.
//!
//! The table is generated at build time so that the Rust binary does not need
//! to read files from disk at runtime. Asset names are content-hashed by Vite,
//! so they can be served with an immutable cache policy.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by Cargo"));
    let dist = manifest_dir.join("web").join("dist");
    println!("cargo:rerun-if-changed={}", dist.display());

    let index = dist.join("index.html");
    if !index.is_file() {
        panic!(
            "the frontend bundle is missing at {}; run `npm ci && npm run build` in crates/pactole-web/web",
            index.display()
        );
    }

    let mut assets = Vec::new();
    collect_assets(&dist, &dist, &mut assets);
    assets.sort_by(|left, right| left.0.cmp(&right.0));

    let mut generated = String::new();
    generated.push_str("// @generated by crates/pactole-web/build.rs; do not edit.\n\n");
    generated.push_str("/// The single-page application entry point served for non-API routes.\n");
    generated.push_str("pub(crate) const INDEX_HTML: &[u8] = include_bytes!(");
    generated.push_str(&rust_string(path_str(&index)));
    generated.push_str(");\n\n");
    generated
        .push_str("/// Content-hashed frontend assets, as `(url path, content type, bytes)`.\n");
    generated.push_str("pub(crate) const ASSETS: &[(&str, &str, &[u8])] = &[\n");
    for (url_path, file) in assets {
        generated.push_str("    (");
        generated.push_str(&rust_string(&url_path));
        generated.push_str(", ");
        generated.push_str(&rust_string(content_type(&file)));
        generated.push_str(", include_bytes!(");
        generated.push_str(&rust_string(path_str(&file)));
        generated.push_str(")),\n");
    }
    generated.push_str("];\n");

    let output = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by Cargo"))
        .join("static_assets.rs");
    fs::write(&output, generated).expect("failed to write the generated static asset table");
}

fn collect_assets(directory: &Path, dist: &Path, assets: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(directory) {
        Ok(entries) => entries,
        Err(error) => panic!(
            "failed to read the frontend asset directory {}: {error}",
            directory.display()
        ),
    };
    for entry in entries {
        let path = entry
            .expect("failed to read a frontend asset directory entry")
            .path();
        if path.is_dir() {
            collect_assets(&path, dist, assets);
        } else if path.is_file() && path.file_name().is_some_and(|name| name != "index.html") {
            let relative = path
                .strip_prefix(dist)
                .expect("a frontend asset must live under web/dist");
            let url_path = format!("/{}", relative.to_string_lossy().replace('\\', "/"));
            assets.push((url_path, path));
        }
    }
}

fn content_type(path: &Path) -> &'static str {
    match path
        .extension()
        .and_then(|extension| extension.to_str())
        .unwrap_or_default()
        .to_ascii_lowercase()
        .as_str()
    {
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "html" => "text/html; charset=utf-8",
        "json" | "map" => "application/json; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "avif" => "image/avif",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "otf" => "font/otf",
        "eot" => "application/vnd.ms-fontobject",
        _ => "application/octet-stream",
    }
}

fn path_str(path: &Path) -> &str {
    path.to_str()
        .unwrap_or_else(|| panic!("frontend path is not valid UTF-8: {}", path.display()))
}

fn rust_string(value: &str) -> String {
    format!("{value:?}")
}
